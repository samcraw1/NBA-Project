CREATE TABLE player_game_stats (
    game_id TEXT NOT NULL REFERENCES games(game_id),
    player_id INTEGER NOT NULL REFERENCES players(player_id),
    team_id INTEGER NOT NULL REFERENCES teams (team_id),
    is_home BOOLEAN,
    zero_minutes BOOLEAN,
    wl TEXT,
    min INTEGER,
    fgm INTEGER,
    fga INTEGER,
    fg3m INTEGER,
    fg3a INTEGER,
    ftm INTEGER,
    fta INTEGER,
    oreb INTEGER,
    dreb INTEGER,
    reb INTEGER,
    ast INTEGER,
    stl INTEGER,
    blk INTEGER,
    tov INTEGER,
    pf INTEGER,
    pts INTEGER,
    plus_minus INTEGER,
    fg_pct NUMERIC,
    fg3_pct NUMERIC,
    ft_pct NUMERIC,
    fantasy_pts NUMERIC,
    PRIMARY KEY (game_id, player_id)
);